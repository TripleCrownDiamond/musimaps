export function useAdminT() {
  const { lang } = useLanguage()
  const t = useCallback(
    (key: AdminKey, params?: Record<string, string | number>) => {
      let template = lang === 'en' ? en[key] : fr[key]
      if (template === undefined) template = fr[key]
      if (params) {
        for (const [name, value] of Object.entries(params)) {
          template = template.replaceAll(`{${name}}`, String(value))
        }
      }
      return template
    },
    [lang],
  )
  return { t, lang }
}
